"""Build map-plate jobs and run the PyQGIS renderer (local QGIS or the Docker image).

This module runs in the engine environment; ``render.py`` runs in the QGIS environment.
"""

import json
import os
import subprocess
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath
from typing import Any

from geovision.core.config import get_settings

CARTO_DIR = Path(__file__).parent
TEMPLATE_A4 = "plate_a4_landscape.qpt"
OSM_BASEMAP = {
    "name": "OpenStreetMap",
    "uri": "type=xyz&url=https://tile.openstreetmap.org/{z}/{x}/{y}.png&zmax=19&zmin=0",
}

# Container paths used when rendering with Docker.
_C_WORK = PurePosixPath("/work")
_C_CARTO = PurePosixPath("/app/src/geovision/carto")


class RenderError(RuntimeError):
    pass


@dataclass
class PlateLayer:
    name: str
    path: Path
    kind: str = "vector"  # vector | raster
    style: str | None = None  # file name in carto/styles, or absolute path


@dataclass
class PlateJob:
    title: str
    subtitle: str
    extent: tuple[float, float, float, float]
    extent_crs: str
    layers: list[PlateLayer]
    output_pdf: Path
    output_png: Path | None = None
    notes: str = ""
    footer: str = "Generated by GeoVision automated screening · Draft for professional review"
    template: str = TEMPLATE_A4
    basemap: dict[str, str] | None = field(default_factory=lambda: dict(OSM_BASEMAP))
    dpi: int = 300
    padding: float = 0.15

    def to_dict(self, work_dir: Path, docker: bool) -> dict[str, Any]:
        def p(path: Path) -> str:
            if not docker:
                return str(path.resolve())
            return str(_C_WORK / path.resolve().relative_to(work_dir.resolve()).as_posix())

        template = (
            str(_C_CARTO / "templates" / self.template)
            if docker
            else str(CARTO_DIR / "templates" / self.template)
        )
        return {
            "template": template,
            "output_pdf": p(self.output_pdf),
            "output_png": p(self.output_png) if self.output_png else None,
            "dpi": self.dpi,
            "extent": list(self.extent),
            "extent_crs": self.extent_crs,
            "padding": self.padding,
            "layers": [
                {"name": lyr.name, "path": p(lyr.path), "kind": lyr.kind, "style": lyr.style}
                for lyr in self.layers
            ],
            "basemap": self.basemap,
            "labels": {
                "Title": self.title,
                "Subtitle": self.subtitle,
                "Notes": self.notes,
                "Footer": self.footer,
            },
        }


def run_plate(job: PlateJob, work_dir: Path, timeout: int = 600) -> Path:
    """Write the job file into ``work_dir`` and render it. All job paths must be inside it."""
    settings = get_settings()
    docker = not settings.qgis_python
    work_dir = work_dir.resolve()
    job_file = work_dir / f"job_{job.output_pdf.stem}.json"
    job_file.write_text(json.dumps(job.to_dict(work_dir, docker), indent=2), encoding="utf-8")

    if docker:
        cmd = [
            "docker", "run", "--rm",
            "-v", f"{work_dir}:{_C_WORK}",
            "-v", f"{CARTO_DIR}:{_C_CARTO}:ro",
            settings.qgis_image,
            "--job", str(_C_WORK / job_file.name),
        ]  # fmt: skip
        env = None
    else:
        # render.py is self-contained (stdlib + qgis), so run it as a script: QGIS launchers
        # reset PYTHONPATH, and the engine venv must not leak into QGIS's Python.
        cmd = [str(settings.qgis_python), str(CARTO_DIR / "render.py"), "--job", str(job_file)]
        env = {k: v for k, v in os.environ.items() if k not in ("VIRTUAL_ENV", "PYTHONHOME")}

    result = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout, env=env)
    if result.returncode != 0 or not job.output_pdf.exists():
        output = f"{result.stdout[-2000:]}\n{result.stderr[-4000:]}"
        raise RenderError(f"Renderer failed ({result.returncode}):\n{output}")
    return job.output_pdf
